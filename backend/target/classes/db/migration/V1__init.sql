/* Flyway migration V1 - Initialize database schema */

CREATE TABLE nguoi_dung (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    ho_ten VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    mat_khau VARCHAR(255) NOT NULL,
    vai_tro VARCHAR(20) NOT NULL
);

CREATE TABLE san_pham (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    ma_san_pham VARCHAR(50) NOT NULL UNIQUE,
    ten_san_pham VARCHAR(200) NOT NULL,
    gia_ban DECIMAL(15,2) NOT NULL,
    gia_von DECIMAL(15,2) NOT NULL,
    so_luong_ton INT NOT NULL,
    danh_muc VARCHAR(100)
);

CREATE TABLE khach_hang (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    ho_ten VARCHAR(100) NOT NULL,
    so_dien_thoai VARCHAR(20),
    email VARCHAR(100),
    dia_chi VARCHAR(255)
);

CREATE TABLE don_hang (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    ma_don_hang VARCHAR(50) NOT NULL UNIQUE,
    khach_hang_id BIGINT NOT NULL,
    tong_tien DECIMAL(15,2) NOT NULL,
    trang_thai VARCHAR(20) NOT NULL,
    ngay_tao DATETIME NOT NULL,
    CONSTRAINT fk_don_hang_khach_hang FOREIGN KEY (khach_hang_id) REFERENCES khach_hang(id) ON DELETE RESTRICT
);

CREATE TABLE chi_tiet_don_hang (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    don_hang_id BIGINT NOT NULL,
    san_pham_id BIGINT NOT NULL,
    so_luong INT NOT NULL,
    gia_ban DECIMAL(15,2) NOT NULL,
    tam_tinh DECIMAL(15,2) NOT NULL,
    CONSTRAINT fk_ctdh_don_hang FOREIGN KEY (don_hang_id) REFERENCES don_hang(id) ON DELETE CASCADE,
    CONSTRAINT fk_ctdh_san_pham FOREIGN KEY (san_pham_id) REFERENCES san_pham(id) ON DELETE RESTRICT
);

